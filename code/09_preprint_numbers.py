#!/usr/bin/env python3
"""Step 9: write every number and table the preprint quotes, from the result files.

Plain-language header: the preprint (paper/preprint/main.tex) never contains a typed
number. It reads paper/preprint/numbers.tex (one LaTeX command per number) and the
tab_*.tex tables written here from paper/geometry.json, paper/synthetic_study.json,
paper/example_run.json and config/params.yaml. Rerun after any change, then rebuild
the PDF (paper/preprint/build.sh).
"""

from __future__ import annotations

import json
import math
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from pitwall.util import load_yaml  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "paper", "preprint")


def pct(x, d=0):
    return "--" if x is None else f"{100 * x:.{d}f}\\%"


def num(x, d=0):
    return "--" if x is None else f"{x:.{d}f}"


def name(s):
    """LaTeX command names may only contain letters."""
    digits = {"0": "Zero", "1": "One", "2": "Two", "3": "Three", "4": "Four", "5": "Five", "6": "Six",
              "7": "Seven", "8": "Eight", "9": "Nine"}
    return "".join(digits.get(ch, ch) for ch in re.sub(r"[^A-Za-z0-9]", "", s))


def cell(A, amp, pre):
    return next(a for a in A if abs(a["amp"] - amp) < 1e-9 and a["precursor"] == pre)


def main():
    final = "--final" in sys.argv
    with open(os.path.join(OUT, "status.tex"), "w") as f:
        f.write("% Generated by code/09_preprint_numbers.py. Draft marker until the author verifies (--final removes it).\n")
        f.write("" if final else "\\preprint{DRAFT for author verification}\n")
    G = json.load(open(os.path.join(ROOT, "paper", "geometry.json")))
    S = json.load(open(os.path.join(ROOT, "paper", "synthetic_study.json")))
    X = json.load(open(os.path.join(ROOT, "paper", "example_run.json")))
    P = load_yaml(os.path.join(ROOT, "config", "params.yaml"))
    C = S["corrected"]
    M = {}

    # ---- parameters
    M["PCoh"] = num(P["coherence_min"], 1)
    M["PWindow"] = num(P["window_days"])
    M["PMinObs"] = num(P["min_obs_in_window"])
    M["PK"] = num(P["k_sigma"], 0)
    M["PFloor"] = num(100 * P["velocity_floor_m_per_yr"], 0)
    M["PCluster"] = num(P["min_cluster_pixels"])
    M["PClusterArea"] = f"{P['min_cluster_pixels'] * 900:,}".replace(",", "{,}")
    M["PPersist"] = num(P["persistence_epochs"])
    M["PLead"] = num(P["lead_window_days"])
    M["PGrace"] = num(P["late_grace_days"])
    M["PBuffer"] = num(P["event_buffer_m"])
    M["PStableMin"] = num(P["stable_min_pixels"])
    M["PCohFrac"] = pct(P["coherent_epoch_frac"])
    M["PWallSlope"] = num(P["auto_wall_slope_min_deg"])
    M["PStableSlope"] = num(P["auto_stable_slope_max_deg"])
    M["PStableGap"] = num(P["auto_stable_gap_m"])
    M["PStableWidth"] = f"{P['auto_stable_width_m']:,.0f}".replace(",", "{,}")
    M["PStableKeep"] = pct(P["auto_stable_keep_frac"])

    # ---- geometry
    def g(inc, slope):
        return next(r for r in G["aspect_summary"] if r["incidence_deg"] == inc and r["slope_deg"] == slope)
    for slope in (35, 45, 55):
        r = g(39.0, float(slope))
        w = {35: "ThirtyFive", 45: "FortyFive", 55: "FiftyFive"}[slope]
        M[f"GeoVisSingle{w}"] = pct(r["ascending"]["frac_visible"])
        M[f"GeoLaySingle{w}"] = pct(r["ascending"]["frac_layover"])
        M[f"GeoShaSingle{w}"] = pct(r["ascending"]["frac_shadow"])
        M[f"GeoSensSingle{w}"] = pct(r["ascending"]["frac_sens_ge_0.5"])
        M[f"GeoBlindSingle{w}"] = pct(r["ascending"]["frac_sens_lt_0.2"])
        M[f"GeoVisEither{w}"] = pct(r["either"]["frac_visible"])
        M[f"GeoSensEither{w}"] = pct(r["either"]["frac_sens_ge_0.5"])
        M[f"GeoBlindEither{w}"] = pct(r["either"]["frac_sens_lt_0.2"])
    pw = G["pilot_walls"]
    de = {r["incidence_deg"]: r for r in pw if r["wall"].startswith("Continental")}
    sg = {r["incidence_deg"]: r for r in pw if r["wall"].startswith("Saga")}
    M["DEastDescMid"] = num(abs(de[39.0]["descending"]["p"]), 2)
    M["DEastAscMid"] = num(abs(de[39.0]["ascending"]["p"]), 2)
    M["SagaMid"] = num(abs(sg[39.0]["ascending"]["p"]), 2)
    M["SagaNear"] = num(abs(sg[30.0]["ascending"]["p"]), 2)
    M["SagaFar"] = num(abs(sg[46.0]["ascending"]["p"]), 2)
    al = {(a["sensor"], a["revisit_days"]): a for a in G["aliasing"]}
    s1 = "Sentinel-1 C-band"
    M["LamC"] = num(al[(s1, 12)]["wavelength_cm"], 2)
    M["QuarterC"] = num(al[(s1, 12)]["max_los_cm_per_revisit"], 2)
    M["AliasSix"] = num(al[(s1, 6)]["max_los_cm_per_yr"])
    M["AliasTwelve"] = num(al[(s1, 12)]["max_los_cm_per_yr"])
    M["AliasTwentyFour"] = num(al[(s1, 24)]["max_los_cm_per_yr"])
    nl = al[("NISAR L-band", 12)]
    M["LamL"] = num(nl["wavelength_cm"], 1)
    M["QuarterL"] = num(nl["max_los_cm_per_revisit"], 2)
    M["AliasNisar"] = num(nl["max_los_cm_per_yr"])
    M["AliasRatio"] = num(nl["max_los_cm_per_yr"] / al[(s1, 12)]["max_los_cm_per_yr"], 1)

    # ---- simulation
    M["NReal"] = f"{S['n_realizations'] + C['n_realizations']:,}".replace(",", "{,}")
    M["NRealArm"] = f"{S['n_realizations']:,}".replace(",", "{,}")
    M["Seeds"] = str(S["seeds_per_cell"])
    M["NoiseDefault"] = num(S["noise_default_cm_per_yr"], 1)
    M["HiddenPx"] = str(S["hidden_wall_visible_px_max"])
    for arm, D in (("", S), ("Cor", C)):
        ch = D["chance"]["k_sweep_12d_w72"]["3.0"]
        M[f"Chance{arm}"] = pct(ch["rate"])
        M[f"FA{arm}"] = num(ch["per_wall_year"], 2)
        for amp, pre, tag in [(0.005, 120, "HalfOneTwenty"), (0.01, 120, "OneOneTwenty"), (0.02, 120, "TwoOneTwenty"),
                              (0.02, 60, "TwoSixty"), (0.04, 120, "FourOneTwenty"), (0.04, 240, "FourTwoForty"),
                              (0.01, 240, "OneTwoForty"), (0.04, 60, "FourSixty")]:
            c_ = cell(D["A_grid"], amp, pre)
            M[f"W{tag}{arm}"] = pct(c_["rate"])
            M[f"L{tag}{arm}"] = num(c_["lead"]["median"])
        kt = {k["k_sigma"]: k for k in D["k_tradeoff"]}
        for k, w in [(2.0, "Two"), (2.5, "TwoHalf"), (3.0, "Three"), (3.5, "ThreeHalf"), (4.0, "Four")]:
            M[f"KW{w}{arm}"] = pct(kt[k]["warned"]["rate"])
            M[f"KFA{w}{arm}"] = num(kt[k]["false_alerts"]["per_wall_year"], 2)
            M[f"KChance{w}{arm}"] = pct(D["chance"]["k_sweep_12d_w72"][str(k)]["rate"])
        bn = {(b["seasonal"], b["k_sigma"]): b for b in D["B_null"]}
        for seas, w in [(0.0, "Zero"), (1.2e-5, "One"), (2.4e-5, "Two"), (4.8e-5, "Four")]:
            M[f"Null{w}{arm}"] = num(bn[(seas, 3.0)]["per_wall_year"], 2)
        for wd in ("48", "72", "120"):
            M[f"ChanceWin{name(wd)}{arm}"] = pct(D["chance"]["window"][wd]["rate"])
            M[f"FAWin{name(wd)}{arm}"] = num(D["chance"]["window"][wd]["per_wall_year"], 2)
            cw = next(c for c in D["C_window"] if c["window_days"] == int(wd) and c["precursor"] == 120)
            M[f"WWin{name(wd)}{arm}"] = pct(cw["rate"])
            M[f"NoiseWin{name(wd)}"] = num(cw["noise_cm_per_yr"], 1)
        M[f"ChanceSix{arm}"] = pct(D["chance"]["revisit6"]["rate"])
        M[f"FASix{arm}"] = num(D["chance"]["revisit6"]["per_wall_year"], 2)
        d6 = next(d for d in D["D_revisit"] if abs(d["amp"] - 0.01) < 1e-9 and d["precursor"] == 120)
        M[f"WSix{arm}"] = pct(d6["r6"]["rate"])
        M[f"LSix{arm}"] = num(d6["lead6"]["median"])
        M["NoiseSix"] = num(d6["noise6_cm_per_yr"], 1)
        for atm in ("2.0", "8.0"):
            M[f"ChanceAtm{name(atm[0])}{arm}"] = pct(D["chance"]["atm"][atm]["rate"])
            M[f"FAAtm{name(atm[0])}{arm}"] = num(D["chance"]["atm"][atm]["per_wall_year"], 2)
            e = next(e for e in D["E_atm"] if abs(e["sigma_atm_mm"] - float(atm)) < 1e-6)
            M[f"WAtm{name(atm[0])}{arm}"] = pct(e["rate"])
            M[f"NoiseAtm{name(atm[0])}"] = num(e["noise_cm_per_yr"], 1)
    k3 = next(k for k in S["k_tradeoff"] if k["k_sigma"] == 3.0)
    k2 = next(k for k in S["k_tradeoff"] if k["k_sigma"] == 2.0)
    M["FAWallYears"] = f"{k3['false_alerts']['wall_years']:,.0f}".replace(",", "{,}")
    M["KPreThree"] = str(k3["warned_before_onset"])
    M["KPreTwo"] = str(k2["warned_before_onset"])
    M["KWarnedThree"] = str(k3["warned"]["k"])
    M["KWarnedTwo"] = str(k2["warned"]["k"])
    M["KNGrid"] = str(k3["warned"]["n"])
    M["NullUnmatchedCor"] = str(sum(b["unmatched"] for b in C["B_null"] if b["k_sigma"] == 3.0))
    M["NullWallYearsCor"] = f"{sum(b['wall_years'] for b in C['B_null'] if b['k_sigma'] == 3.0):,.0f}".replace(",", "{,}")
    M["MissFourSixty"] = str(cell(S["A_grid"], 0.04, 60)["outcomes"].get("missed", 0))
    M["MissFourSixtyCor"] = str(cell(C["A_grid"], 0.04, 60)["outcomes"].get("missed", 0))
    M["MissTwoAll"] = str(sum(cell(S["A_grid"], 0.02, pre)["outcomes"].get("missed", 0) for pre in (60, 120, 240)))
    M["ExampleNorthAlerts"] = str(X.get("north_alerts", 0))
    M["ExampleSouthAlerts"] = str(X.get("south_alerts", 0))
    M["ExampleLead"] = num(X["lead_days"]) if X.get("lead_days") is not None else "--"

    with open(os.path.join(OUT, "numbers.tex"), "w") as f:
        f.write("% Generated by code/09_preprint_numbers.py from the result files. Do not edit by hand.\n")
        for k, v in sorted(M.items()):
            f.write(f"\\newcommand{{\\{k}}}{{{v}}}\n")

    # ---- tables
    def write(name_, body):
        with open(os.path.join(OUT, name_), "w") as f:
            f.write("% Generated by code/09_preprint_numbers.py. Do not edit by hand.\n" + body)

    rows = []
    for a in G["aliasing"]:
        rows.append(f"{a['sensor'].replace('Sentinel-1', 'Sentinel-1').replace(' band', '-band')} & {a['wavelength_cm']:.2f} & "
                    f"{a['revisit_days']} & {a['max_los_cm_per_revisit']:.2f} & {a['max_los_cm_per_yr']:.0f} \\\\")
    write("tab_alias.tex", "\n".join(rows) + "\n")

    rows = []
    for inc in (30.0, 39.0, 46.0):
        for slope in (35.0, 45.0, 55.0):
            r = g(inc, slope)
            a_, e_ = r["ascending"], r["either"]
            rows.append(f"{inc:.0f} & {slope:.0f} & {pct(a_['frac_visible'])} & {pct(a_['frac_layover'])} & "
                        f"{pct(a_['frac_shadow'])} & {pct(a_['frac_sens_ge_0.5'])} & {pct(e_['frac_visible'])} & "
                        f"{pct(e_['frac_sens_ge_0.5'])} \\\\")
        if inc != 46.0:
            rows.append("\\hline")
    write("tab_geom.tex", "\n".join(rows) + "\n")

    rows = []
    for wall, dd in (("Continental, D East (faces W)", de), ("Saga, north wall (faces S)", sg)):
        for inc in (30.0, 39.0, 46.0):
            r = dd[inc]
            fmt = lambda q: f"{q['p']:+.2f} ({q['vis']})"  # noqa: E731
            rows.append(f"{wall if inc == 30.0 else ''} & {inc:.0f} & {fmt(r['ascending'])} & {fmt(r['descending'])} \\\\")
        if wall.startswith("Continental"):
            rows.append("\\hline")
    write("tab_pilotwalls.tex", "\n".join(rows) + "\n")

    rows = []
    for amp in (0.005, 0.01, 0.02, 0.04):
        for pre in (60, 120, 240):
            u, c_ = cell(S["A_grid"], amp, pre), cell(C["A_grid"], amp, pre)
            lead = lambda x: "--" if x["lead"]["median"] is None else f"{x['lead']['median']:.0f} ({x['lead']['q25']:.0f}--{x['lead']['q75']:.0f})"  # noqa: E731
            rows.append(f"{100 * amp:g} & {pre} & {u['total_creep_cm']:.1f} & {u['v_mid_cm_per_yr']:.1f} & "
                        f"{100 * u['rate']:.0f} ({100 * u['ci95'][0]:.0f}--{100 * u['ci95'][1]:.0f}) & {lead(u)} & "
                        f"{100 * c_['rate']:.0f} & {lead(c_)} \\\\")
        if amp != 0.04:
            rows.append("\\hline")
    write("tab_grid.tex", "\n".join(rows) + "\n")

    def var_row(label, noise, chu, fau, wu, chc, fac, wc):
        return f"{label} & {noise} & {chu} & {fau} & {wu} & {chc} & {fac} & {wc} \\\\"
    base_u, base_c = cell(S["A_grid"], 0.01, 120), cell(C["A_grid"], 0.01, 120)
    rows = [var_row("Baseline (12 d, 72 d, 4 mm)", num(S["noise_default_cm_per_yr"], 1),
                    pct(S["chance"]["k_sweep_12d_w72"]["3.0"]["rate"]), num(S["chance"]["k_sweep_12d_w72"]["3.0"]["per_wall_year"], 2),
                    pct(base_u["rate"]), pct(C["chance"]["k_sweep_12d_w72"]["3.0"]["rate"]),
                    num(C["chance"]["k_sweep_12d_w72"]["3.0"]["per_wall_year"], 2), pct(base_c["rate"]))]
    for wd in ("48", "120"):
        cu = next(c for c in S["C_window"] if c["window_days"] == int(wd) and c["precursor"] == 120)
        cc = next(c for c in C["C_window"] if c["window_days"] == int(wd) and c["precursor"] == 120)
        rows.append(var_row(f"Window {wd} d", num(cu["noise_cm_per_yr"], 1), pct(S["chance"]["window"][wd]["rate"]),
                            num(S["chance"]["window"][wd]["per_wall_year"], 2), pct(cu["rate"]),
                            pct(C["chance"]["window"][wd]["rate"]), num(C["chance"]["window"][wd]["per_wall_year"], 2),
                            pct(cc["rate"])))
    du = next(d for d in S["D_revisit"] if abs(d["amp"] - 0.01) < 1e-9 and d["precursor"] == 120)
    dc = next(d for d in C["D_revisit"] if abs(d["amp"] - 0.01) < 1e-9 and d["precursor"] == 120)
    rows.append(var_row("Revisit 6 d", num(du["noise6_cm_per_yr"], 1), pct(S["chance"]["revisit6"]["rate"]),
                        num(S["chance"]["revisit6"]["per_wall_year"], 2), pct(du["r6"]["rate"]),
                        pct(C["chance"]["revisit6"]["rate"]), num(C["chance"]["revisit6"]["per_wall_year"], 2),
                        pct(dc["r6"]["rate"])))
    for atm in ("2.0", "8.0"):
        eu = next(e for e in S["E_atm"] if abs(e["sigma_atm_mm"] - float(atm)) < 1e-6)
        ec = next(e for e in C["E_atm"] if abs(e["sigma_atm_mm"] - float(atm)) < 1e-6)
        rows.append(var_row(f"Turbulence {float(atm):.0f} mm", num(eu["noise_cm_per_yr"], 1),
                            pct(S["chance"]["atm"][atm]["rate"]), num(S["chance"]["atm"][atm]["per_wall_year"], 2),
                            pct(eu["rate"]), pct(C["chance"]["atm"][atm]["rate"]),
                            num(C["chance"]["atm"][atm]["per_wall_year"], 2), pct(ec["rate"])))
    write("tab_variants.tex", "\n".join(rows) + "\n")

    rows = []
    for k_u, k_c in zip(S["k_tradeoff"], C["k_tradeoff"]):
        k = k_u["k_sigma"]
        rows.append(f"{k:g} & {pct(k_u['warned']['rate'])} & {pct(S['chance']['k_sweep_12d_w72'][str(k)]['rate'])} & "
                    f"{k_u['false_alerts']['per_wall_year']:.2f} & {pct(k_c['warned']['rate'])} & "
                    f"{pct(C['chance']['k_sweep_12d_w72'][str(k)]['rate'])} & {k_c['false_alerts']['per_wall_year']:.2f} \\\\")
    write("tab_k.tex", "\n".join(rows) + "\n")
    print(f"numbers.tex: {len(M)} values; tables written")


if __name__ == "__main__":
    main()
